public class Movie {

    // 영화 제목
    private String title;

    // 영화 장르
    private String genre;

    // 개봉 연도
    private int releaseYear;

    // 생성자
    public Movie(String title, String genre, int releaseYear) {
        this.title = title;
        this.genre = genre;
        this.releaseYear = releaseYear;
    }
}
